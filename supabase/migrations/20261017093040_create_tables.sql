-- Phase 4 step 1: core tables, alert trigger, indexes.
--
-- RLS is switched on for every table here, before any policy exists, so each
-- table starts deny-all for anon/authenticated. Policies come in the next
-- migration. The API writes with the service role, which bypasses RLS.

-- ---------------------------------------------------------------------------
-- transactions: one row per scored transaction (written by the API)
-- ---------------------------------------------------------------------------
create table public.transactions (
    id            uuid primary key,                 -- generated by the API, returned to the caller
    created_at    timestamptz not null default now(),
    time_seconds  double precision not null check (time_seconds >= 0),  -- raw dataset `Time`
    amount        numeric(12, 2) not null check (amount >= 0),
    hour_of_day   smallint not null check (hour_of_day between 0 and 23),
    features      jsonb not null check (jsonb_typeof(features) = 'object'),  -- V1..V28
    probability   double precision not null check (probability between 0 and 1),
    risk_level    text not null check (risk_level in ('LOW', 'MEDIUM', 'HIGH')),
    reasons       jsonb not null default '[]'::jsonb check (jsonb_typeof(reasons) = 'array'),
    model_version text not null,
    latency_ms    real check (latency_ms >= 0)
);

comment on table public.transactions is 'Every transaction scored by the API.';
comment on column public.transactions.time_seconds is 'Seconds since the first dataset transaction; needed to re-score for /explain/{id}.';
comment on column public.transactions.features is 'Anonymized PCA features V1-V28 as a JSON object.';

-- ---------------------------------------------------------------------------
-- alerts: one per MEDIUM/HIGH transaction, reviewed by analysts
-- ---------------------------------------------------------------------------
create table public.alerts (
    id             bigint generated always as identity primary key,
    transaction_id uuid not null unique references public.transactions (id) on delete cascade,
    severity       text not null check (severity in ('HIGH', 'MEDIUM')),
    status         text not null default 'open'
                   check (status in ('open', 'confirmed_fraud', 'false_alarm')),
    reviewed_by    uuid references auth.users (id) on delete set null,
    reviewed_at    timestamptz,
    created_at     timestamptz not null default now()
);

comment on table public.alerts is 'Review queue: created automatically for MEDIUM and HIGH transactions.';

-- ---------------------------------------------------------------------------
-- feedback: analyst verdicts on alerts (future training labels)
-- ---------------------------------------------------------------------------
create table public.feedback (
    id         bigint generated always as identity primary key,
    alert_id   bigint not null references public.alerts (id) on delete cascade,
    label      text not null check (label in ('confirmed_fraud', 'false_alarm')),
    note       text check (char_length(note) <= 2000),
    analyst    uuid not null default auth.uid() references auth.users (id) on delete cascade,
    created_at timestamptz not null default now()
);

comment on table public.feedback is 'Analyst verdicts on alerts.';

-- ---------------------------------------------------------------------------
-- model_runs: trained model versions and their metrics (from metadata.json)
-- ---------------------------------------------------------------------------
create table public.model_runs (
    id         bigint generated always as identity primary key,
    version    text not null unique,
    metrics    jsonb not null check (jsonb_typeof(metrics) = 'object'),
    trained_at timestamptz not null,
    created_at timestamptz not null default now()
);

comment on table public.model_runs is 'One row per trained model version (loaded by scripts/load_model_runs.py).';

-- ---------------------------------------------------------------------------
-- Alert trigger: MEDIUM/HIGH transactions get an alert in the same database
-- transaction, so a risky row can never be stored without its alert.
-- ---------------------------------------------------------------------------
create function public.create_alert_for_risky_transaction()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.risk_level in ('HIGH', 'MEDIUM') then
        insert into public.alerts (transaction_id, severity)
        values (new.id, new.risk_level);
    end if;
    return new;
end;
$$;

revoke execute on function public.create_alert_for_risky_transaction() from public, anon, authenticated;

create trigger transactions_create_alert
after insert on public.transactions
for each row execute function public.create_alert_for_risky_transaction();

-- ---------------------------------------------------------------------------
-- Indexes for the dashboard's common queries (+ every foreign key)
-- ---------------------------------------------------------------------------
create index transactions_created_at_idx on public.transactions (created_at desc);           -- live feed
create index transactions_risk_created_idx on public.transactions (risk_level, created_at desc); -- filter by risk
create index alerts_status_created_idx on public.alerts (status, created_at desc);           -- review queue
create index alerts_reviewed_by_idx on public.alerts (reviewed_by);
create index feedback_alert_id_idx on public.feedback (alert_id);
create index feedback_analyst_idx on public.feedback (analyst);
-- alerts.transaction_id is already indexed by its unique constraint.

-- ---------------------------------------------------------------------------
-- Row Level Security on from the start (deny-all until policies are added)
-- ---------------------------------------------------------------------------
alter table public.transactions enable row level security;
alter table public.alerts enable row level security;
alter table public.feedback enable row level security;
alter table public.model_runs enable row level security;
